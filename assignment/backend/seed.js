async function addAdmin() {
  const email = process.env.ADMIN_EMAIL;
  const password = process.env.ADMIN_PASSWORD;
  if (!email || !password) return;

  const exists = await Admin.findOne({ email: email.toLowerCase() });
  if (exists) return;

  await Admin.create({ email, password: await bcrypt.hash(password, 10) });
  console.log("Admin account saved");
}

async function fillIfEmpty() {
  await addAdmin();
  await Product.deleteMany({});
  await User.deleteMany({});
  await Order.deleteMany({});
  await Product.insertMany(products);
  await User.insertMany(users);
  await Order.insertMany(orders);
  console.log("Starter data saved");
}

async function reseed() {
  await connectDB();
  await Product.deleteMany({});
  await User.deleteMany({});
  await Order.deleteMany({});
  await Product.insertMany(products);
  await User.insertMany(users);
  await Order.insertMany(orders);
  await addAdmin();
  console.log("Database reset. Products, users, and orders saved.");
  await mongoose.disconnect();
}

if (require.main === module) {
  reseed().catch((error) => {
    console.log("Could not seed MongoDB Atlas.");
    console.log(error.message);
    process.exit(1);
  });
}

